-- The index behind the Legion facts consumer's read of the stored rows a pull request's change
-- left with a merge no pull request backs (dispatch://INFRA-2916, R21, legionfacts.lostMerges). A
-- stored row's merged_at is the earliest merge of its issue's pull requests, and the attribution
-- moves a pull request to another issue, or to none, by rewriting its issue_key
-- (delivery.AttributePullRequests). The change row that write logs names the repository, the
-- number and the merge times alone (0100), so the issue the pull request left is found by the
-- merge it held before the change: `... from issue_facts where merged_at = any($1) and merged_at
-- is not null`, each merge a probe of this index answering the rows stored with that merge.
-- Without it the read is a scan of the whole table, every project's every row, on each page of
-- changes that holds a pull request's. The rows with no merge (every open issue's, and every
-- issue's no pull request names) are left out, as delivery_pull_requests_merged_at (0080) leaves
-- them out of the pull requests.
--
-- A plain build in the runner's transaction, as 20261117100009's on issue_facts is: issue_facts
-- holds one row per issue Legion worked, 8.5 MB for 28,000 rows in the measurement that migration
-- cites, far below the census's 1 GiB bound on a table a migration locks
-- (pgmigrate.CensusTableLimit). The build holds SHARE on issue_facts for one read of it, which
-- holds the writes of the table's one writer, the Legion facts consumer, and no read.
--
-- The release before this one neither reads nor writes the index, and an index decides a plan and
-- never an answer, so it rolls beside this one. It refuses and rewrites no row; its census
-- answers 0.
create index issue_facts_merged on issue_facts (merged_at) where merged_at is not null;
