-- #4065: the repository that holds a result's commit, where that is not the repository the
-- check's issue resolves to (api/results.go, recordCheckResult).
--
--   commit_repo   the canonical `owner/repo` the record route found holding the commit
--                 (refuseUnknownCommit), stored only where it is a repository the check's
--                 issue links a pull request in and not the repository that issue resolved to
--                 at the write; null for every other row. A result at the merge commit of a
--                 pull request the issue links in a second repository names a commit of that
--                 repository, and the results read compares an `after_merge` or a
--                 `default_branch` result with that repository's branches where the column
--                 names one (api/results_comparison.go, onNamedBranch). Asked of the issue's
--                 own repository, GitHub answers 404 for such a commit and the result reads
--                 unknown.
--
-- A row recorded before this migration carries null here, and so does every result at a commit
-- of the issue's own repository: the read compares such a row in the repository the check's
-- issue resolves to, as the release before this one compares every row, at the same cost. No
-- backfill writes the column: which repository held a stored row's commit is GitHub's to say,
-- and a census that rewrites a row refuses the deploy (cmd/dispatch/README.md, "Pre-deploy
-- census").
--
-- Adding a nullable column with no default is a catalog change that rewrites no row. The ALTER
-- takes ACCESS EXCLUSIVE on check_results, which every recorded result writes and every results
-- read reads, and holds it only for the catalog write. It must first wait for every transaction
-- that holds the table: the runner bounds that wait at pgmigrate.LockTimeout (five seconds) and
-- tries again up to pgmigrate.LockTimeoutAttempts times, after which the migration fails the
-- boot, and every write queued behind the ALTER waits as long as it does.
--
-- The release before this one neither reads nor writes the column, so the two roll side by side
-- (cmd/dispatch/README.md, "Database migrations"): a result that release records during the roll
-- carries null and is compared as it compares every row. Rolling back past this migration is an
-- image rollback alone; the column left behind is read by nothing.
alter table check_results add column commit_repo text;
