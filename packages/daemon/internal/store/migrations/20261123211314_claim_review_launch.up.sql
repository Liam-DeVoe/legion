-- 20261123211314_claim_review_launch.up.sql — the head a reviewer's launch gave it, kept on the
-- claim's row, so a daemon that restarts knows where a live reviewer's own clone stands (R18 of
-- the one-App verdict spec, the review's H1).
--
-- claims.review_launch_head is supervise.Claim.ReviewLaunchHead: the head the launch that started
-- the reviewer's process gave it (runtime.SpawnSpec.ReviewHead, '' for a launch given none), at
-- which that launch made or moved the reviewer's own clone; nothing moves the clone while the
-- process runs. claims.review_launch_generation is supervise.Claim.ReviewLaunchGeneration, that
-- launch's generation. The machine sets both as it builds a reviewer's launch (spawnSpec), and they
-- reach the store with the write that records the process the launch started (launchNow). Before
-- each send to a reviewer, and before each message the daemon holds for one, the machine compares
-- the head the record holds for the issue's pull request with this one, read only where the
-- generation is the claim's own (reviewHeadHolds): where they differ the process is started again
-- at the record's head first. Kept on the row, the comparison survives a restart of the daemon,
-- which re-adopts a live reviewer and hands it its next task in the process it found where the
-- head has not moved. Every other role leaves both at their defaults.
--
-- Every row the table already holds takes the defaults, '' and 0: generation 0 names no launch, so
-- the next task of a live reviewer an earlier release launched waits for a launch at the record's
-- head, which brings its clone there, once.
--
-- Rolling the image back needs no restore of the schema. The release before this one names
-- neither column in any statement (the claim store's claimSelect and upsertClaim), so it neither
-- reads them nor writes them, and its upserts leave whatever they last held. Every launch it makes
-- moves claims.generation past the generation recorded here, and generations only rise, so at the
-- roll-forward a head this release recorded is read for no process the earlier release started:
-- that reviewer's next task waits for a launch at the record's head, as on a row this migration
-- gave its defaults. The roll-forward's Migrate finds this migration's row and the two columns
-- standing, and runs nothing.
--
-- There is no down file: migrations here are forward-only.
alter table claims add column review_launch_head text not null default '';
alter table claims add column review_launch_generation bigint not null default 0;
