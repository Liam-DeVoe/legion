#!/usr/bin/env bash
# Writes gh_stack_git_options.go beside this script: every option word the gh-stack release the
# worker image pins (packages/daemon/docker/worker.Dockerfile, ARG GH_STACK_TOOL) and the cli/cli
# git client its go.mod names pass to git, read from their Go sources, each a string literal that
# starts with `-`. `legion gh-stack-git` lets gh-stack's git take an argument that starts with `-`
# only where it is one of these words, or starts with one of the `--option=` prefixes among them
# (gh_stack_shim.go). Run it again whenever the pin moves; TestGhStackGitOptionsAreThePinnedReleases
# fails until it has been.
#
# It reads the two repositories at their tags over the network, and needs git, go and grep.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
dockerfile="$here/../../docker/worker.Dockerfile"
version="$(sed -n 's|^ARG GH_STACK_TOOL=github:github/gh-stack@||p' "$dockerfile")"
[ -n "$version" ] || { echo "no ARG GH_STACK_TOOL pin of github/gh-stack in $dockerfile" >&2; exit 1; }

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
git clone --quiet --depth 1 --branch "v$version" https://github.com/github/gh-stack "$work/gh-stack"
cli="$(sed -n 's|^[[:space:]]*github.com/cli/cli/v2 \(v[^ ]*\).*|\1|p' "$work/gh-stack/go.mod")"
[ -n "$cli" ] || { echo "gh-stack v$version's go.mod names no github.com/cli/cli/v2" >&2; exit 1; }
git clone --quiet --depth 1 --branch "$cli" https://github.com/cli/cli "$work/cli"

# The sources that build git's argv: gh-stack's internal/git and the cli/cli git package it runs
# git through (cligit.Client). The literal's closing quote ends the word; a word with `=` is kept
# up to and including it, as a prefix.
words="$(
  find "$work/gh-stack/internal/git" "$work/cli/git" -name '*.go' ! -name '*_test.go' -print0 |
    xargs -0 grep -ohE '"-{1,2}([A-Za-z][-A-Za-z0-9]*(=[^"]*)?)?"' |
    sed -e 's/^"//' -e 's/"$//' -e 's/=.*/=/' | LC_ALL=C sort -u
)"
[ -n "$words" ] || { echo "found no option word in gh-stack v$version or cli/cli $cli" >&2; exit 1; }

{
  echo "// Code generated by gh_stack_git_options.sh from github/gh-stack v$version and cli/cli $cli; DO NOT EDIT."
  echo
  echo "package main"
  echo
  echo "// ghStackGitOptionsVersion is the gh-stack release ghStackGitOptions was read from."
  echo "const ghStackGitOptionsVersion = \"$version\""
  echo
  echo "// ghStackGitOptions are the option words gh-stack v$version and cli/cli $cli pass to git: a"
  echo "// word that ends in \`=\` is a prefix of the word git is passed."
  echo "var ghStackGitOptions = []string{"
  while IFS= read -r word; do
    printf '\t"%s",\n' "$word"
  done <<<"$words"
  echo "}"
} >"$here/gh_stack_git_options.go"
gofmt -w "$here/gh_stack_git_options.go"
echo "wrote $here/gh_stack_git_options.go: $(wc -l <<<"$words") words from gh-stack v$version and cli/cli $cli"
