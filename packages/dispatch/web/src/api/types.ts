/** One issue as the issue page reads it (`api.getIssue`): the issue's own read with every member
 *  its `include` adds - its open asks, its children, its progress, its design gates, where its
 *  route reaches (`reach`) and how many items cite it. The route answers each only as it is asked
 *  for, so the document marks each optional; this names the read that asked for all of them. */
export type IssueDetails = IssueReadV2 &
  Required<
    Pick<
      IssueReadV2,
      "children" | "design_gates" | "open_asks" | "progress" | "reach" | "referenced_by_count"
    >
  >;

/** One ask read with its thread (`include=thread`): its replies, rewordings, answers, followers,
 *  claimant and route. The route answers the thread only as it is asked for, so the document
 *  marks it optional; this names the read that asked for it. */
export type AskWithThread = AskV2 & { readonly thread: AskThread };

/** One ask as the Inbox lists it (`api.getInbox`): with its thread and the viewer's own mark on
 *  it, which holds their snooze (`include=thread,mark`). */
export type InboxRow = AskWithThread & { readonly mark: AskMarkV2 };

/** One document read with its text (`include=text`): its markdown, the token a write of it goes
 *  under and whether that markdown is a version's. `version` is the version it stands on, absent
 *  for a document with none. */
export type ArtifactText = ArtifactV2 & {
  readonly markdown: string;
  readonly token: string;
  readonly unsettled: boolean;
};

/** The person's marks of one kind by the id each names - an issue's key, a session's id - as the
 *  page reads one object's state by its id. `GET /api/v2/me/marks` lists them; this is that list
 *  keyed, which is how `["user-state"]` and `["user-agent-state"]` hold them. */
export type Marks = Readonly<Record<string, MarkV2>>;

/** A collaborator session the Legion registry knows: its `legion` entry is never absent. Both
 *  readers that keep such sessions apart from the rest - the Collaborators tab's Legion sections
 *  and the composer's "Not running" options - narrow to this with a type guard of their own, so
 *  the narrowed shape is named once here. */
export type IssueCollaboratorLegionAgent = CollaboratorV2 & {
  readonly kind: "session";
  readonly session_id: string;
  readonly legion: IssueCollaboratorLegion;
};
